// Generate implements sqlc's CodegenService.Generate hook.
func Generate(_ context.Context, req *plugin.GenerateRequest) (*plugin.GenerateResponse, error) {
	opts, err := parseOptions(req)
	if err != nil {
		return nil, fmt.Errorf("parse options: %w", err)
	}

	queries, imports, err := querySpecs(req, opts)
	if err != nil {
		return nil, fmt.Errorf("build query specifications: %w", err)
	}

	files, err := generateWrapper(opts, queries, imports)
	if err != nil {
		return nil, fmt.Errorf("generate wrappers: %w", err)
	}
	return &plugin.GenerateResponse{Files: files}, nil
}
